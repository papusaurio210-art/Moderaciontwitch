import { test, expect } from '@playwright/test';
import { createRoom, upload, socketRequest, panelUrl, overlayUrl } from './helpers';
import type { RoomState } from '../../src/shared/model';

test('ocultos editables: selección, arrastre, bloqueo, opacidad y persistencia entre editores', async ({ page, context, request }) => {
  const room = await createRoom(request);
  await page.goto(panelUrl(room));
  await expect(page.getByText('Conectado', { exact: true })).toBeVisible();
  const media = await upload(page, request, room);
  const added = await socketRequest(page, room, { t: 'item.add', mediaId: media.id, x: 100, y: 100 });
  const id = added.op.item.id;
  const other = await context.newPage(); await other.goto(panelUrl(room));
  const viewer = await context.newPage(); await viewer.goto(overlayUrl(room));
  const item = page.locator('.canvas-item');
  await item.click();
  const opacity = page.getByRole('spinbutton', { name: 'Opacidad', exact: true });
  await opacity.fill('60'); await opacity.press('Enter');
  await expect(viewer.locator('.overlay-item')).toHaveCSS('opacity', '0.6');
  await page.getByRole('button', { name: 'Ocultar elemento', exact: true }).click();
  await expect(viewer.locator('.overlay-item')).toHaveCount(0);
  await expect(other.locator('.hidden-item-label')).toHaveText('Oculto');
  await expect(item.locator('.canvas-item-content')).toHaveCSS('opacity', '0.25');
  await expect(opacity).toHaveValue('60');
  await page.keyboard.press('Escape');
  await expect(item).not.toHaveClass(/selected/);
  const bounds = (await item.boundingBox())!;
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + 40, bounds.y + bounds.height / 2 + 25, { steps: 5 }); await page.mouse.up();
  await expect(item).toHaveClass(/selected/);
  await expect.poll(async () => (await socketRequest(page, room) as RoomState).items[0].x).toBeGreaterThan(100);
  await expect(viewer.locator('.overlay-item')).toHaveCount(0);
  const width = page.getByRole('spinbutton', { name: 'Ancho', exact: true });
  await width.fill('500'); await width.press('Enter');
  await expect(other.locator('.canvas-item')).toHaveCSS('width', '500px');
  await page.getByRole('button', { name: 'Bloquear elemento', exact: true }).click();
  await expect(width).toBeDisabled();
  const locked = (await socketRequest(page, room) as RoomState).items[0];
  await page.keyboard.press('ArrowRight');
  expect((await socketRequest(page, room) as RoomState).items[0].x).toBe(locked.x);
  await page.getByRole('button', { name: 'Desbloquear elemento', exact: true }).click();
  await expect(width).toBeEnabled();
  await page.reload(); await viewer.reload();
  await expect(item.locator('.hidden-item-label')).toHaveText('Oculto');
  await expect(viewer.getByTestId('overlay-stage')).toBeVisible();
  await expect(viewer.locator('.overlay-item')).toHaveCount(0);
  await item.click();
  await expect(opacity).toHaveValue('60');
  await page.getByRole('button', { name: 'Mostrar elemento', exact: true }).click();
  await expect(viewer.locator('.overlay-item')).toHaveCSS('opacity', '0.6');
  await expect(item.locator('.canvas-item-content')).toHaveCSS('opacity', '0.6');
  await expect(other.locator('.hidden-item-label')).toHaveCount(0);
  await expect(viewer.locator('.hidden-item-label')).toHaveCount(0);
  // Even a hidden item whose saved opacity is zero remains locatable/editable.
  await opacity.fill('0'); await opacity.press('Enter');
  await expect(viewer.locator('.overlay-item')).toHaveCSS('opacity', '0');
  await page.getByRole('button', { name: 'Ocultar elemento', exact: true }).click();
  await expect(item.locator('.canvas-item-content')).toHaveCSS('opacity', '0.25');
  await expect(item.locator('.hidden-item-label')).toBeVisible();
  await expect(opacity).toHaveValue('0');
  await page.screenshot({ path: 'test-results/hidden-item-editor.png', fullPage: true });
  await page.getByRole('button', { name: 'Mostrar elemento', exact: true }).click();
  await expect(viewer.locator('.overlay-item')).toHaveCSS('opacity', '0');
  expect((await socketRequest(page, room) as RoomState).items[0]).toMatchObject({ id, visible: true, opacity: 0, w: 500 });
  await other.close(); await viewer.close();
});
